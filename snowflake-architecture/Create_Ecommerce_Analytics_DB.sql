--Create DB & Schema:-

CREATE DATABASE ECOMMERCE_ANALYTICS_DB;

CREATE SCHEMA ECOMMERCE_ANALYTICS_DB.PROFITABILITY_ANALYSIS;

SHOW TABLES IN SCHEMA PROFITABILITY_ANALYSIS;

--Create FILE_FORMATE & STAGE so that we can insert data into our Stage:-

CREATE OR REPLACE FILE FORMAT
    ECOMMERCE_ANALYTICS_DB.PROFITABILITY_ANALYSIS.CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('NULL', 'null')
    EMPTY_FIELD_AS_NULL = TRUE
    DATE_FORMAT = 'DD-MM-YYYY';

CREATE STAGE
    ECOMMERCE_ANALYTICS_DB.PROFITABILITY_ANALYSIS.ECOM_STAGE
    FILE_FORMAT =
    ECOMMERCE_ANALYTICS_DB.PROFITABILITY_ANALYSIS.CSV_FORMAT;

SHOW STAGES;

LIST @ECOM_STAGE;
