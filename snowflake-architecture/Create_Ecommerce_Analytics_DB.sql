--Create Tables:-

--1. Dim_Date Table:-
CREATE TABLE ECOMMERCE_ANALYTICS_DB.PROFITABILITY_ANALYSIS.DIM_DATE (
Date_Key NUMERIC (8,0) Primary Key,
Full_Date DATE,	
Year NUMERIC (4,0),	
Quarter VARCHAR(3),	
Month_Number NUMERIC(3,0),	
Month_Name VARCHAR(15),	
Year_Month VARCHAR(10),	
Week_Number	NUMERIC(3,0),	
Day_Of_Month NUMERIC(2,0),	
Day_Name VARCHAR(10),	
Is_Weekend BOOLEAN	
);

-- 2. DIM_CUSTOMER
CREATE TABLE ECOMMERCE_ANALYTICS_DB.PROFITABILITY_ANALYSIS.DIM_CUSTOMER (
    CUSTOMER_ID VARCHAR(20) PRIMARY KEY,
    FIRST_NAME VARCHAR(100),
    LAST_NAME VARCHAR(100),
    GENDER VARCHAR(20),
    DOB DATE,
    SIGNUP_DATE DATE,
    CITY VARCHAR(100),
    STATE VARCHAR(100),
    CUSTOMER_SEGMENT VARCHAR(50),
    ACQUISITION_CHANNEL VARCHAR(50)
);

-- 3. DIM_PRODUCT
CREATE TABLE ECOMMERCE_ANALYTICS_DB.PROFITABILITY_ANALYSIS.DIM_PRODUCT (
    PRODUCT_ID VARCHAR(20) PRIMARY KEY,
    PRODUCT_NAME VARCHAR(200),
    CATEGORY VARCHAR(100),
    SUBCATEGORY VARCHAR(100),
    BRAND VARCHAR(100),
    UNIT_PRICE NUMBER(12,2),
    UNIT_COST NUMBER(12,2),
    LAUNCH_DATE DATE,
    IS_ACTIVE BOOLEAN
);

-- 4. DIM_ORDER
CREATE TABLE ECOMMERCE_ANALYTICS_DB.PROFITABILITY_ANALYSIS.DIM_ORDER (
    ORDER_ID VARCHAR(30) PRIMARY KEY,
    ORDER_DATE_KEY NUMERIC (8,0),
    CUSTOMER_ID VARCHAR(20),
    SALES_CHANNEL VARCHAR(50),
    PAYMENT_METHOD VARCHAR(50),
    ORDER_STATUS VARCHAR(20),
    SHIPPING_CITY VARCHAR(100),
    SHIPPING_STATE VARCHAR(100),
    DELIVERY_DATE DATE,
    SHIPPING_DAYS INT,

    FOREIGN KEY (ORDER_DATE_KEY)
        REFERENCES ECOMMERCE_ANALYTICS_DB.PROFITABILITY_ANALYSIS.DIM_DATE(DATE_KEY),

    FOREIGN KEY (CUSTOMER_ID)
        REFERENCES ECOMMERCE_ANALYTICS_DB.PROFITABILITY_ANALYSIS.DIM_CUSTOMER(CUSTOMER_ID)
);

-- 5. FACT_ORDER_ITEMS
CREATE TABLE ECOMMERCE_ANALYTICS_DB.PROFITABILITY_ANALYSIS.FACT_ORDER_ITEMS (
    ORDER_ID VARCHAR(30),
    LINE_ID INT,
    PRODUCT_ID VARCHAR(20),
    QUANTITY INT,
    UNIT_SELLING_PRICE NUMBER(12,2),
    GROSS_SALES NUMBER(14,2),
    DISCOUNT_RATE NUMBER(7,4),
    DISCOUNT_AMOUNT NUMBER(14,2),
    NET_SALES NUMBER(14,2),
    UNIT_COST NUMBER(12,2),
    TOTAL_COST NUMBER(14,2),
    PROFIT NUMBER(14,2),
    LINE_STATUS VARCHAR(20),

    PRIMARY KEY (ORDER_ID, LINE_ID),

    FOREIGN KEY (ORDER_ID)
        REFERENCES DIM_ORDER(ORDER_ID),

    FOREIGN KEY (PRODUCT_ID)
        REFERENCES DIM_PRODUCT(PRODUCT_ID)
);

